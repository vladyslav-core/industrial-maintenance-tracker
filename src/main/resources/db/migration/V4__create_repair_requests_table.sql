CREATE TABLE repair_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    title VARCHAR(150) NOT NULL,
    description VARCHAR(3000) NOT NULL,
    equipment_id BIGINT NOT NULL,
    created_by_id BIGINT NOT NULL,
    assigned_technician_id BIGINT,
    priority VARCHAR(20) NOT NULL DEFAULT 'MEDIUM',
    status VARCHAR(20) NOT NULL DEFAULT 'NEW',
    resolution TEXT,
    cancellation_reason VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    assigned_at TIMESTAMP WITH TIME ZONE,
    started_at TIMESTAMP WITH TIME ZONE,
    completed_at TIMESTAMP WITH TIME ZONE,
    closed_at TIMESTAMP WITH TIME ZONE,

    CONSTRAINT pk_repair_requests PRIMARY KEY (id),
    CONSTRAINT fk_repair_requests_equipment
        FOREIGN KEY (equipment_id) REFERENCES equipment (id),
    CONSTRAINT fk_repair_requests_created_by
        FOREIGN KEY (created_by_id) REFERENCES users (id),
    CONSTRAINT fk_repair_requests_assigned_technician
        FOREIGN KEY (assigned_technician_id) REFERENCES users (id),

    CONSTRAINT ck_repair_requests_title
        CHECK (CHAR_LENGTH(title) BETWEEN 5 AND 150 AND title = BTRIM(title)),
    CONSTRAINT ck_repair_requests_description
        CHECK (CHAR_LENGTH(description) BETWEEN 10 AND 3000
            AND description = BTRIM(description)),
    CONSTRAINT ck_repair_requests_priority
        CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_repair_requests_status
        CHECK (status IN (
            'NEW', 'ASSIGNED', 'IN_PROGRESS', 'COMPLETED', 'CLOSED', 'CANCELLED'
        )),
    CONSTRAINT ck_repair_requests_resolution
        CHECK (resolution IS NULL OR (
            CHAR_LENGTH(BTRIM(resolution)) > 0
            AND resolution = BTRIM(resolution)
        )),
    CONSTRAINT ck_repair_requests_cancellation_reason
        CHECK (cancellation_reason IS NULL OR (
            CHAR_LENGTH(cancellation_reason) BETWEEN 5 AND 500
            AND cancellation_reason = BTRIM(cancellation_reason)
        )),
    CONSTRAINT ck_repair_requests_required_result
        CHECK (status NOT IN ('COMPLETED', 'CLOSED') OR resolution IS NOT NULL),
    CONSTRAINT ck_repair_requests_required_cancellation
        CHECK (status <> 'CANCELLED' OR cancellation_reason IS NOT NULL),
    CONSTRAINT ck_repair_requests_assigned_state
        CHECK (status NOT IN ('ASSIGNED', 'IN_PROGRESS', 'COMPLETED', 'CLOSED')
            OR (assigned_technician_id IS NOT NULL AND assigned_at IS NOT NULL)),
    CONSTRAINT ck_repair_requests_dates
        CHECK (
            (status <> 'NEW' OR (
                assigned_technician_id IS NULL AND assigned_at IS NULL
                AND started_at IS NULL AND completed_at IS NULL AND closed_at IS NULL
            ))
            AND (status <> 'ASSIGNED' OR (
                started_at IS NULL AND completed_at IS NULL AND closed_at IS NULL
            ))
            AND (status <> 'IN_PROGRESS' OR (
                started_at IS NOT NULL AND completed_at IS NULL AND closed_at IS NULL
            ))
            AND (status <> 'COMPLETED' OR (
                started_at IS NOT NULL AND completed_at IS NOT NULL AND closed_at IS NULL
            ))
            AND (status <> 'CLOSED' OR (
                started_at IS NOT NULL AND completed_at IS NOT NULL AND closed_at IS NOT NULL
            ))
            AND (status <> 'CANCELLED' OR (
                completed_at IS NULL AND closed_at IS NOT NULL
            ))
        )
);

CREATE INDEX ix_repair_requests_equipment_status
    ON repair_requests (equipment_id, status);

CREATE INDEX ix_repair_requests_created_by_created_at
    ON repair_requests (created_by_id, created_at DESC, id DESC);

CREATE INDEX ix_repair_requests_assigned_technician_status
    ON repair_requests (assigned_technician_id, status);
